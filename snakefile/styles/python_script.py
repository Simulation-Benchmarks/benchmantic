"""
snakefile.styles.python_script

For implementations that are a Python script or notebook with the inputs
written in the code (the `python` input format): the Snakefile copies the
implementation folder (next to it, else the folder it was described from,
else a clone of the repository it came from), writes each mapped benchmark parameter into the
code's constants, adds a few lines that write the metrics -- values of the
code's variables when it ends -- to solution_metrics.json, and runs the copy
(a notebook is run as its code cells). Nothing in the repository has to
change for this. The helpers doing it (software/formats/python_code_runtime.py)
are copied into the Snakefile, so it needs nothing of benchmantic.

Settings in the software description (`run:`, with `type: script`):
  script: main.py                  the file to run (default: the file the
                                   implementation link points at, else the
                                   first input file)
  command: "python3 {script}"      how to run it in the container; {script}
                                   is the prepared copy
  setup: "source /opt/env.sh"      shell lines run first
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

from snakefile.renderer import parameter_assignments
from software.base import SnakefileContext, SnakefileResult

RUNTIME_FILE = Path(__file__).resolve().parents[2] / "software" / "formats" / "python_code_runtime.py"
#: The prepared copy of the script that the container runs.
RUN_FILE = "benchmantic_run.py"


def add_arguments(group) -> None:
    """No options of its own."""


def build_hints(adapter, module_dir: Path, repo_root: Path) -> dict[str, Any]:
    script = adapter.script_file(module_dir)
    return {
        "script": str(script.relative_to(module_dir)) if script else None,
        "metric_expressions": adapter.metric_expressions(module_dir, repo_root),
    }


def _runtime_source() -> str:
    """python_code_runtime.py without its license header."""
    lines = RUNTIME_FILE.read_text(encoding="utf-8").splitlines()
    while lines and lines[0].startswith("#"):
        lines.pop(0)
    return "\n".join(lines).strip() + "\n"


def render_mapped(adapter, mapping: dict[str, Any], hints: dict[str, Any], args,
                  units: dict[str, str], unit_symbols: dict[str, str]) -> str:
    settings = adapter.run_settings
    script = hints.get("script")
    if not script:
        sys.exit("Error: no script to run -- set `script` under `run:` in the software description.")
    inputs = [i for i in mapping["inputs"] if i.get("expression")]
    names = sorted({n for i in inputs for n in i.get("benchmark_parameters", [])})
    by_file: dict[str, list[str]] = {}
    for i in inputs:
        by_file.setdefault(i["section"], []).append(f"        {i['key']!r}: f{i['expression']!r},")
    code_inputs = "\n".join(f"    {section!r}: {{\n" + "\n".join(lines) + "\n    },"
                            for section, lines in by_file.items())
    metrics = hints.get("metric_expressions") or {}
    code_metrics = "\n".join(f"    {k!r}: {v!r}," for k, v in metrics.items())
    command = settings.get("command", "python3 {script}").replace("{script}", RUN_FILE)
    setup = "\n            ".join((settings.get("setup") or ":").rstrip("\n").splitlines())

    head = f'''\
# Generated by benchmantic from the input mapping ({adapter.name}): the
# benchmark's software-neutral parameters are read from parameters.json and
# written into a copy of the implementation's code (see *_mapping.json); the
# copy is run, and the metrics are values of the code's variables when it
# ends. Run it in a folder holding parameters.json, as run_benchmark.py
# prepares it.
import json
import shutil
import subprocess
from pathlib import Path

snakefile_dir = Path(workflow.snakefile).resolve().parent
# The implementation folder (holding {script}): the Snakefile's folder when it
# sits there (as in the benchmark repositories), else the folder it was
# described from, else a clone of the repository it came from, made next to
# the Snakefile on the first run.
implementation_dir = snakefile_dir
local_implementation = {hints.get("local_implementation")!r}
repository = {hints.get("repository")!r}
repository_ref = {hints.get("repository_ref")!r}
implementation_path = {hints.get("module_relative_path") or "."!r}
container_image = {args.container_image!r}

with open("parameters.json") as f:
    config = json.load(f)
conf_name = config.get('configuration', 'case')

# benchmark parameters
{parameter_assignments(names, units, unit_symbols)}

# the code's constants, set from the benchmark parameters: {{file: {{name: value}}}}
code_inputs = {{
{code_inputs}
}}
# the metrics: Python expressions over the code's variables when it ends
code_metrics = {{
{code_metrics}
}}
code_script = {script!r}

'''
    rules = f'''

rule all:
    input:
        "solution_metrics.json"

rule run_simulation:
    input:
        "parameters.json"
    output:
        "solution_metrics.json"
    resources:
        serial_run=1
    singularity:
        f"docker://{{container_image}}"
    run:
        # 1. a copy of the implementation, with this case's values in its code
        source = implementation_dir
        if not (source / code_script).is_file() and local_implementation:
            source = Path(local_implementation)
        if not (source / code_script).is_file():
            if not repository:
                raise FileNotFoundError(f"{{code_script}} is not next to the Snakefile; set implementation_dir")
            clone = snakefile_dir / ".implementation"
            if not clone.is_dir():
                branch = ["--branch", repository_ref] if repository_ref else []
                subprocess.run(["git", "clone", "--depth", "1", *branch, repository, str(clone)], check=True)
            source = clone / implementation_path
        work = Path("work")
        shutil.rmtree(work, ignore_errors=True)        # a fresh copy each run
        shutil.copytree(source, work,
                        ignore=shutil.ignore_patterns("Snakefile", ".snakemake", ".git", "work", "results"))
        for name, values in code_inputs.items():
            if name != code_script:
                path = work / name
                path.write_text(set_constants(code_view(path.read_text(), path.suffix == ".ipynb"), values))
        main = work / code_script
        code = set_constants(code_view(main.read_text(), main.suffix == ".ipynb"), code_inputs.get(code_script, {{}}))
        # 2. ... that writes the metrics when it ends (unless the code writes them itself)
        if code_metrics:
            code += metrics_footer(code_metrics, str(Path("solution_metrics.json").resolve()))
        (work / {RUN_FILE!r}).write_text(code)
        # 3. run it
        shell(
            f"""
            set -euo pipefail
            cd work
            {setup}
            {command}
            """
        )
'''
    runtime = "# --- helpers (benchmantic's software/formats/python_code_runtime.py) ---\n" + _runtime_source()
    return head + runtime + rules


def render(adapter, ctx: SnakefileContext) -> SnakefileResult:
    mapping, hints = ctx.mapping, ctx.build_hints
    if not mapping:
        sys.exit(
            f"Error: {adapter.name} Snakefiles are generated from the input mapping (*_mapping.json next to "
            f"{ctx.metadata_jsonld.name}), and there is none -- the 'snakefile-only' output preset and "
            "--parameter-names software don't write one. Describe the benchmark with neutral parameter "
            "names (the default) to get one."
        )
    text = render_mapped(adapter, mapping, hints, ctx.args, ctx.units, ctx.unit_symbols)
    mapped = [i["input"] for i in mapping["inputs"] if i.get("expression")]
    metrics = hints.get("metric_expressions") or {}
    summary = (
        f"\n{len(ctx.cases)} case(s), {len(mapped)} mapped input(s): {', '.join(mapped)}\n"
        f"script  = {hints.get('script')} (run as {RUN_FILE}: "
        f"{adapter.run_settings.get('command', 'python3 {script}').replace('{script}', RUN_FILE)})\n"
        f"metrics = " + (", ".join(f"{k} = {v}" for k, v in metrics.items()) or "(none)")
    )
    return SnakefileResult(text=text, summary=[summary], note=f" ({adapter.name}, from {ctx.mapping_file.name})")
