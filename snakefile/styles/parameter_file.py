"""
snakefile.styles.parameter_file

For implementations whose program reads a parameter file given on its
command line (e.g. `python3 run_simulation.py --input_parameter_file
parameters_1.json ...`), with one such file per case (`cases.files`). The
Snakefile copies the implementation (with the folder holding the case
files), writes a parameter file for the case -- the template case's file
with each mapped benchmark parameter set, keeping its layout ("value"/"unit"
objects stay) -- and runs the command in the implementation folder.

Settings in the software description (`run:`, with `type: parameter_file`):
  command: "python3 run.py --input_parameter_file {parameter_file} --output_metrics_file {metrics_file}"
        run in the implementation folder; {parameter_file} is the case's
        parameter file, {metrics_file} where solution_metrics.json must go
        (a solution_metrics.json the command writes in its folder is
        collected too), {configuration} the case's name. Several steps can
        be joined with &&, e.g. a mesh generator first.
  setup: "source /opt/env.sh"      shell lines run first
"""

from __future__ import annotations

import os
import sys
from pathlib import Path
from typing import Any

from snakefile.renderer import parameter_assignments
from software.base import SnakefileContext, SnakefileResult

#: The case's parameter file the Snakefile writes, in the implementation folder.
RUN_FILE = "benchmantic_parameters.json"


def add_arguments(group) -> None:
    """No options of its own."""


def build_hints(adapter, module_dir: Path, repo_root: Path) -> dict[str, Any]:
    cases = adapter.discover_cases(module_dir)
    sources = getattr(adapter, "case_sources", {})
    if not sources:
        sys.exit("Error: run.type parameter_file needs the case files named in the software description "
                 "(cases.files, e.g. \"parameters_*.json\").")
    folder = adapter.case_files_folder(module_dir)
    copy_root = Path(os.path.commonpath([module_dir.resolve(), folder]))
    template_id = cases[0][1]
    return {
        # (a local implementation whose case files sit above the folder given is
        # never cloned, so a copy_root outside the "repository" does no harm)
        "copy_root": os.path.relpath(copy_root, repo_root.resolve()),
        "local_copy_root": str(copy_root),
        "implementation_in_copy": str(module_dir.resolve().relative_to(copy_root)),
        "template_case_file": str(sources[template_id].resolve().relative_to(copy_root)),
        "case_files": {cid: str(p.resolve().relative_to(copy_root)) for cid, p in sources.items()},
    }


def render_mapped(adapter, mapping: dict[str, Any], hints: dict[str, Any], args,
                  units: dict[str, str], unit_symbols: dict[str, str]) -> str:
    settings = adapter.run_settings
    command = settings.get("command")
    if not command or "{parameter_file}" not in command:
        sys.exit("Error: run.command in the software description must pass {parameter_file} to the program.")
    inputs = [i for i in mapping["inputs"] if i.get("expression")]
    names = sorted({n for i in inputs for n in i.get("benchmark_parameters", [])})
    entries = "\n".join(f"    {i['key']!r}: f{i['expression']!r}," for i in inputs)
    setup = (settings.get("setup") or ":").strip()

    return f'''\
# Generated by benchmantic from the input mapping ({adapter.name}): the
# benchmark's software-neutral parameters are read from parameters.json and
# written into a copy of the implementation's parameter file (see
# *_mapping.json), which the program is given on its command line. Run it in a
# folder holding parameters.json, as run_benchmark.py prepares it.
import json
import shutil
import subprocess
from pathlib import Path

snakefile_dir = Path(workflow.snakefile).resolve().parent
# The implementation, with the folder holding its case files: next to the
# Snakefile when it sits there, else the folder it was described from, else
# a clone of the repository it came from, made next to the Snakefile.
repository = {hints.get("repository")!r}
repository_ref = {hints.get("repository_ref")!r}
copy_root = {hints.get("copy_root", ".")!r}                   # in the repository
local_copy_root = {hints.get("local_copy_root")!r}
implementation_in_copy = {hints.get("implementation_in_copy", ".")!r}
template_case_file = {hints.get("template_case_file")!r}      # the parameter file the case's is made from
container_image = {args.container_image!r}

with open("parameters.json") as f:
    config = json.load(f)
conf_name = config.get('configuration', 'case')

# benchmark parameters
{parameter_assignments(names, units, unit_symbols)}

# the parameter file's entries, set from the benchmark parameters: {{"key/path": value}}
file_entries = {{
{entries}
}}
command = {command!r}
setup = {setup!r}


def as_value(text, old):
    """A value as written into the parameter file, of the old value's type."""
    if isinstance(old, bool):
        return str(text).lower() in ("1", "true", "yes")
    if isinstance(old, (int, float)):
        number = float(text)
        return int(number) if isinstance(old, int) and number.is_integer() else number
    if isinstance(old, list):
        return [as_value(t, old[0] if old else 0.0) for t in str(text).replace(",", " ").split()]
    return str(text)


def set_entry(data, path, text):
    node = data
    *parents, last = path.split("/")
    for name in parents:
        node = node[name]
    if isinstance(node[last], dict) and "value" in node[last]:
        node[last]["value"] = as_value(text, node[last]["value"])
    else:
        node[last] = as_value(text, node[last])


def implementation_source():
    if (snakefile_dir / template_case_file).is_file():
        return snakefile_dir
    if local_copy_root and (Path(local_copy_root) / template_case_file).is_file():
        return Path(local_copy_root)
    if not repository:
        raise FileNotFoundError(f"{{template_case_file}} not found next to the Snakefile")
    clone = snakefile_dir / ".implementation"
    if not clone.is_dir():
        branch = ["--branch", repository_ref] if repository_ref else []
        subprocess.run(["git", "clone", "--depth", "1", *branch, repository, str(clone)], check=True)
    return clone / copy_root


rule all:
    input:
        "solution_metrics.json"

rule run_simulation:
    input:
        "parameters.json"
    output:
        "solution_metrics.json"
    resources:
        serial_run=1
    singularity:
        f"docker://{{container_image}}"
    run:
        # 1. a fresh copy of the implementation
        work = Path("work")
        shutil.rmtree(work, ignore_errors=True)
        shutil.copytree(implementation_source(), work,
                        ignore=shutil.ignore_patterns(".git", ".snakemake", ".benchmantic", ".implementation",
                                                      "work", "Snakefile"))
        # 2. the case's parameter file: the template's, with this case's values
        data = json.loads((work / template_case_file).read_text())
        if "configuration" in data:
            data["configuration"] = conf_name
        for path, text in file_entries.items():
            set_entry(data, path, text)
        run_dir = (work / implementation_in_copy).resolve()
        parameter_file = run_dir / {RUN_FILE!r}
        parameter_file.write_text(json.dumps(data, indent=4))
        metrics_file = Path("solution_metrics.json").resolve()
        # 3. run the program on it
        cmd = command.format(parameter_file=parameter_file, metrics_file=metrics_file, configuration=conf_name)
        script = f"set -euo pipefail\\ncd '{{run_dir}}'\\n{{setup}}\\n{{cmd}}\\n"
        shell(script.replace("{{", "{{{{").replace("}}", "}}}}"))
        written = run_dir / "solution_metrics.json"
        if not metrics_file.exists() and written.exists():
            shutil.copy(written, metrics_file)
'''


def render(adapter, ctx: SnakefileContext) -> SnakefileResult:
    mapping, hints = ctx.mapping, ctx.build_hints
    if not mapping:
        sys.exit(
            f"Error: {adapter.name} Snakefiles are generated from the input mapping (*_mapping.json next to "
            f"{ctx.metadata_jsonld.name}), and there is none -- the 'snakefile-only' output preset and "
            "--parameter-names software don't write one. Describe the benchmark with neutral parameter "
            "names (the default) to get one."
        )
    text = render_mapped(adapter, mapping, hints, ctx.args, ctx.units, ctx.unit_symbols)
    mapped = [i["input"] for i in mapping["inputs"] if i.get("expression")]
    summary = (
        f"\n{len(ctx.cases)} case(s), {len(mapped)} mapped input(s): {', '.join(mapped)}\n"
        f"parameter file = {hints.get('template_case_file')} (the case's: {RUN_FILE})\n"
        f"command        = {adapter.run_settings.get('command')}"
    )
    return SnakefileResult(text=text, summary=[summary], note=f" ({adapter.name}, from {ctx.mapping_file.name})")
