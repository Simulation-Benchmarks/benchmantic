"""Validate a semantic benchmark description.

1. SHACL: the description must conform to the shapes shipped with
   semantic-benchmark.
2. Loading: semantic_benchmark.BenchmarkLoader must load it with at least
   one configuration, a value on every parameter and at least one metric.

Generated by benchmantic (create_benchmark_repo.py).
"""

import sys
from pathlib import Path

from pyshacl import validate
from rdflib import Graph
from semantic_benchmark.semantics import BenchmarkLoader


def main(path: Path) -> int:
    data = Graph().parse(path, format="json-ld")
    conforms, _, report = validate(data, shacl_graph=BenchmarkLoader.load_shapes(), inference="none")
    if not conforms:
        print(report)
        return 1
    print(f"SHACL: {path} conforms to the semantic-benchmark shapes")

    benchmark = BenchmarkLoader(path).load()
    configurations = [c for c in benchmark.parameter_sets if c.identifier]
    problems = []
    if not configurations:
        problems.append("no configuration (m4i:ParameterSet with an identifier)")
    if not benchmark.evaluates:
        problems.append("no metric")
    for configuration in configurations:
        for parameter in configuration.parts:
            value = getattr(parameter, "numerical_value", None)
            if value is None:
                value = getattr(parameter, "string_value", None)
            if value is None:
                problems.append(f"{configuration.identifier}: {parameter.label} has no value")
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    print(f"Loaded: {len(configurations)} configuration(s), "
          f"{len(benchmark.evaluates)} metric(s): {', '.join(m.label for m in benchmark.evaluates)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(Path(sys.argv[1])))
