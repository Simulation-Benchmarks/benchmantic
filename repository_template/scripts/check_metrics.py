"""Check that every configuration of a benchmark run wrote its metrics.

Reads <results>/<configuration>/solution_metrics.json for each configuration
of the benchmark file and fails unless each one holds a finite number for
every metric the benchmark evaluates. Writes a Markdown table of the values
to --summary (e.g. $GITHUB_STEP_SUMMARY) when given.

Generated by benchmantic (create_benchmark_repo.py).
"""

import argparse
import json
import math
import sys
from pathlib import Path

from semantic_benchmark.semantics import BenchmarkLoader


def lookup(values, json_path):
    """values["a"]["b"] for the JSON path "/a/b/" (or a bare key)."""
    for key in [k for k in str(json_path).split("/") if k]:
        if not isinstance(values, dict) or key not in values:
            return None
        values = values[key]
    return values


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--benchmark-file", type=Path, required=True)
    parser.add_argument("--results", type=Path, required=True,
                        help="folder holding one sub-folder per configuration")
    parser.add_argument("--software", default="")
    parser.add_argument("--summary", type=Path, default=None)
    args = parser.parse_args()

    benchmark = BenchmarkLoader(args.benchmark_file).load()
    # each metric is read from solution_metrics.json at its declared JSON path
    metrics = {m.label: (m.field_mapping.json_path if m.field_mapping and m.field_mapping.json_path
                         else m.label) for m in benchmark.evaluates}
    configurations = [c.identifier for c in benchmark.parameter_sets if c.identifier]

    rows, problems = [], []
    for configuration in configurations:
        path = args.results / configuration / "solution_metrics.json"
        if not path.is_file():
            problems.append(f"{configuration}: {path} is missing")
            continue
        values = json.loads(path.read_text())
        row = []
        for metric, json_path in metrics.items():
            value = lookup(values, json_path)
            if not isinstance(value, (int, float)) or not math.isfinite(value):
                problems.append(f"{configuration}: metric {metric!r} is {value!r}")
            row.append(value)
        rows.append((configuration, row))

    table = [f"### {args.software} results".strip(), "",
             "| configuration | " + " | ".join(metrics) + " |",
             "|---|" + "---:|" * len(metrics)]
    for configuration, row in rows:
        table.append(f"| {configuration} | " + " | ".join(
            f"{v:.4e}" if isinstance(v, (int, float)) else str(v) for v in row) + " |")
    text = "\n".join(table) + "\n"
    print(text)
    if args.summary:
        with args.summary.open("a") as f:
            f.write(text)

    if problems:
        print("Missing or invalid metrics:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1
    print(f"All {len(configurations)} configuration(s) wrote {len(metrics)} metric(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
